export interface ProvinceStat {
  /** 地图 GeoJSON 全称 */
  name: string
  /** 简称 */
  shortName: string
  lit: number
  total: number
  ratio: number
}

/** 计算每个省级行政区的点亮统计（ratio = 已点亮 / 总地级行政区） */
export function provinceStats(lit: Set<string>): ProvinceStat[] {
  return PROVINCES.map((p) => {
    const litCount = p.cities.filter((c) => lit.has(c)).length
    return {
      name: p.fullName,
      shortName: p.name,
      lit: litCount,
      total: p.cities.length,
      ratio: p.cities.length > 0 ? litCount / p.cities.length : 0,
    }
  })
}
